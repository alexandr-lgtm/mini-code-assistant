const HEADER = `// Generated by tools/generate-characters.cjs from DiceBear "Bottts" (https://www.dicebear.com/styles/bottts/),
// design by Pablo Stanley (https://bottts.com/), "free for personal and commercial use". Regenerate rather than edit.
`

fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })

const constName = id => id.toUpperCase().replace(/[^A-Z0-9]/g, '_')

for (const [id, , , color, face, sides, top, texture] of CHARACTERS) {
  const moods = {}
  for (const [mood, { eyes, mouth }] of Object.entries(MOODS)) {
    moods[mood] = createAvatar(bottts, {
      seed: id,
      baseColor: [color],
      face: [face],
      sides: [sides],
      top: [top],
      eyes: [eyes],
      mouth: [mouth],
      mouthProbability: 100,
      sidesProbability: 100,
      topProbability: 100,
      texture: texture ? [texture] : [],
      textureProbability: texture ? 100 : 0,
      size: 96,
    }).toString()
  }
  const body = `${HEADER}
import type { MiniMood } from '../../types'

export const ${constName(id)}: Record<MiniMood, string> = ${JSON.stringify(moods, null, 1)}
`
  fs.writeFileSync(path.join(OUT, `${id}.ts`), body)
}

const index = `${HEADER}
import type { MiniMood } from '../../types'
${CHARACTERS.map(([id]) => `import { ${constName(id)} } from './${id}'`).join('\n')}

export type MiniCharacter = { id: string; name: { ru: string; en: string }; moods: Record<MiniMood, string> }

export const CHARACTERS: MiniCharacter[] = [
${CHARACTERS.map(([id, ru, en]) => `  { id: '${id}', name: { ru: '${ru}', en: '${en}' }, moods: ${constName(id)} },`).join('\n')}
]
`
fs.writeFileSync(path.join(OUT, 'index.ts'), index)
